import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(await readFile(path.join(root, 'design/tokens.json'), 'utf8'));
const value = (token) => typeof token.value === 'string' ? token.value : token.value.dark;
const colors = tokens.color.tokens;
const spacing = tokens.spacing.tokens;
const radii = tokens.radius.tokens;
const sizes = tokens.size.tokens;
const shadow = tokens.shadow.tokens;
const cssVariables = [
  ...colors.map((token) => `  --${token.name}: ${value(token)};`),
  ...spacing.map((token) => `  --${token.name}: ${token.value};`),
  ...radii.map((token) => `  --${token.name}: ${token.value};`),
  ...sizes.map((token) => `  --${token.name}: ${token.value};`),
  ...shadow.map((token) => `  --${token.name}: ${value(token)};`),
  '  --font-sans: "Geist Variable", ui-sans-serif, system-ui, -apple-system, "Helvetica Neue", Arial, sans-serif;',
  '  --font-mono: "Geist Mono Variable", ui-monospace, Menlo, monospace;',
].join('\n');
// Utilities come straight from tokens.json (space-N -> p-N, gap-N, ...), plus 0 and 1px for resets and hairlines.
const spacingUtilities = ['  --spacing-0: 0px;', '  --spacing-px: 1px;',
  ...spacing.map((token) => `  --spacing-${token.name.replace('space-', '')}: ${token.value};`)].join('\n');
const typeName = (name) => name === 'title-lg' ? 'display' : name === 'overline' ? 'label' : name;
const theme = [
  '  --color-*: initial;', '  --spacing-*: initial;', '  --radius-*: initial;',
  '  --shadow-*: initial;', '  --font-*: initial;',
  ...colors.map((token) => `  --color-${token.name}: var(--${token.name});`),
  spacingUtilities,
  ...radii.map((token) => `  --radius-${token.name.replace('radius-', '')}: ${token.value};`),
  '  --font-sans: \"Geist Variable\", ui-sans-serif, system-ui, -apple-system, \"Helvetica Neue\", Arial, sans-serif;', '  --font-mono: \"Geist Mono Variable\", ui-monospace, Menlo, monospace;',
  ...shadow.map((token) => `  --shadow-${token.name.replace('shadow-', '')}: ${value(token)};`),
  ...tokens.type.groups.flatMap((group) => group.styles.map((style) => `  --text-${typeName(style.name)}: ${style.fontSize};\n  --text-${typeName(style.name)}--line-height: ${style.lineHeight};\n  --text-${typeName(style.name)}--font-weight: ${style.fontWeight};${style.letterSpacing ? `\n  --text-${typeName(style.name)}--letter-spacing: ${style.letterSpacing};` : ''}`)),
].join('\n');
const raw = Object.fromEntries([
  ...colors.map((token) => [token.name, value(token)]),
  ...spacing.map((token) => [token.name, token.value]),
  ...radii.map((token) => [token.name, token.value]),
  ...sizes.map((token) => [token.name, token.value]),
  ...shadow.map((token) => [token.name, value(token)]),
  ['font-sans', 'Geist Variable'], ['font-mono', 'Geist Mono Variable'],
  ['type', Object.fromEntries(tokens.type.groups.flatMap((group) => group.styles.map((style) => [style.name, { fontSize: style.fontSize, lineHeight: style.lineHeight, fontWeight: style.fontWeight, ...(style.letterSpacing ? { letterSpacing: style.letterSpacing } : {}) }])))],
]);;
const ts = `// Generated by scripts/gen-tokens.mjs. Do not edit.\nexport const tokens = ${JSON.stringify(raw, null, 2)} as const;\nexport type Tokens = typeof tokens;\n`;
await Promise.all([
  writeFile(path.join(root, 'src/styles/tokens.css'), `/* Generated by scripts/gen-tokens.mjs. Do not edit. */\n:root {\n${cssVariables}\n}\n\n@theme {\n${theme}\n}\n`),
  writeFile(path.join(root, 'src/styles/tokens.ts'), ts),
]);
